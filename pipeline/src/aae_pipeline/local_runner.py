    def max_aggregate_difference(
        expected: list[dict[str, Any]],
        actual: list[dict[str, Any]],
    ) -> float:
        key_fields = ("school_year", "period_id", "area_id")
        numeric_fields = (
            "alarm_seconds_average_school_location",
            "available_school_seconds_average_school_location",
            "expected_school_seconds_average_school_location",
            "school_time_under_alarm_pct",
            "affected_school_days_average_school_location",
            "available_school_days_average_school_location",
            "expected_school_days_average_school_location",
        )
        actual_by_key = {tuple(row[field] for field in key_fields): row for row in actual}
        maximum = 0.0
        if len(expected) != len(actual):
            return float("inf")
        for expected_row in expected:
            key = tuple(expected_row[field] for field in key_fields)
            actual_row = actual_by_key.get(key)
            if actual_row is None:
                return float("inf")
            for field in numeric_fields:
                maximum = max(
                    maximum,
                    abs(float(expected_row.get(field) or 0) - float(actual_row.get(field) or 0)),
                )
        return maximum

