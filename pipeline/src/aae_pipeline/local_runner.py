    def month_year_reconciliation(
        monthly: list[dict[str, Any]],
        yearly: list[dict[str, Any]],
        area_field: str,
        alarm_field: str,
    ) -> float:
        sums: dict[tuple[str, str], float] = {}
        for row in monthly:
            key = (row["school_year"], row[area_field])
            sums[key] = sums.get(key, 0.0) + float(row.get(alarm_field) or 0)
        return max(
            [
                abs(
                    sums.get((row["school_year"], row[area_field]), 0.0)
                    - float(row.get(alarm_field) or 0)
                )
                for row in yearly
            ]
            or [0.0]
        )

